import { readFileSync, writeFileSync } from "fs";
import path from "path";

// Writes the DrawRegistry ABI into the core package as a typed const
const artifact = JSON.parse(
  readFileSync(path.join(__dirname, "../artifacts/contracts/DrawRegistry.sol/DrawRegistry.json"), "utf8"),
);
const out = `// Generated by contracts/scripts/export-abi.ts; do not edit by hand\nexport const drawRegistryAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
writeFileSync(path.join(__dirname, "../../packages/core/src/abi.ts"), out);
console.log(`Wrote ${artifact.abi.length} ABI items`);
